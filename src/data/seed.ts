const nowIso = () => new Date().toISOString();
const daysAgo = (days: number) => new Date(Date.now() - days * 24 * 60 * 60 * 1000).toISOString();

function hashSeed(value: string) {
  let hash = 2166136261;
  for (let index = 0; index < value.length; index += 1) {
    hash ^= value.charCodeAt(index);
    hash = Math.imul(hash, 16777619);
  }
  return hash >>> 0;
}

function freshnessScore(lastUpdate: string) {
  const diffDays = Math.max(0, Math.floor((Date.now() - new Date(lastUpdate).getTime()) / (24 * 60 * 60 * 1000)));
  if (diffDays <= 3) return 100;
  if (diffDays <= 7) return 96;
  if (diffDays <= 14) return 88;
  if (diffDays <= 21) return 74;
  if (diffDays <= 30) return 58;
  return 36;
}

