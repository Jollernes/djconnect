export function getAvailability(djId: string, date: string): DJAvailability["status"] {
  const seed = hashSeed(`${djId}:${date}`);
  const day = new Date(date).getDay();
  const score = seed % 100;
  if (day === 5 || day === 6) {
    if (score < 45) return "available";
    if (score < 65) return "tentative";
    if (score < 88) return "booked";
    return "unavailable";
  }
  if (score < 60) return "available";
  if (score < 72) return "tentative";
  if (score < 87) return "booked";
  return "unavailable";
}

export function listSeedAvailability(djId: string, from = new Date(), days = DEFAULT_AVAILABILITY_DAYS): DJAvailability[] {
  const items: DJAvailability[] = [];
  for (let offset = 0; offset < days; offset += 1) {
    const date = new Date(from.getTime() + offset * 24 * 60 * 60 * 1000);
    const isoDate = date.toISOString().slice(0, 10);
    items.push({
      id: `${djId}_${isoDate}`,
      dj_id: djId,
      date: isoDate,
      status: getAvailability(djId, isoDate),
      notes: null,
      updated_at: nowIso(),
    });
  }
  return items;
}
